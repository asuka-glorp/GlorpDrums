#!/usr/bin/env python3
"""
GlorpDrums - Automated Sample Ripper: Audio Slicer & DrumGizmo Kit Builder
Takes:
  1. rendered_audio.wav (exported from Ardour, Reaper, or any DAW)
  2. sampling_manifest.json (generated by make_sampling_midi.py)
Outputs:
  A fully formatted, production-ready DrumGizmo drumkit ready to load into GlorpDrums:
    - 24-bit stereo WAV samples
    - Per-instrument XML files with velocity power layers
    - drumkit.xml with choke routing
    - midimap.xml matching standard General MIDI
"""

import sys
import os
import json
import wave
import struct
import math

def read_wav_frames(path):
    with wave.open(path, 'r') as wf:
        n_channels = wf.getnchannels()
        sampwidth = wf.getsampwidth()
        rate = wf.getframerate()
        n_frames = wf.getnframes()
        raw_data = wf.readframes(n_frames)

    samples = []
    # Decode samples to float [-1.0, 1.0]
    if sampwidth == 2: # 16-bit
        fmt = f"<{n_frames * n_channels}h"
        int_data = struct.unpack(fmt, raw_data)
        scale = 1.0 / 32768.0
        for i in range(0, len(int_data), n_channels):
            l = int_data[i] * scale
            r = int_data[i + 1] * scale if n_channels > 1 else l
            samples.append((l, r))
    elif sampwidth == 3: # 24-bit
        scale = 1.0 / 8388608.0
        step = 3 * n_channels
        for i in range(0, len(raw_data), step):
            bl = raw_data[i:i+3]
            il = int.from_bytes(bl, byteorder='little', signed=True)
            if n_channels > 1:
                br = raw_data[i+3:i+6]
                ir = int.from_bytes(br, byteorder='little', signed=True)
            else:
                ir = il
            samples.append((il * scale, ir * scale))
    elif sampwidth == 4: # 32-bit int
        fmt = f"<{n_frames * n_channels}i"
        int_data = struct.unpack(fmt, raw_data)
        scale = 1.0 / 2147483648.0
        for i in range(0, len(int_data), n_channels):
            l = int_data[i] * scale
            r = int_data[i + 1] * scale if n_channels > 1 else l
            samples.append((l, r))
    else:
        raise ValueError(f"Unsupported sample width: {sampwidth} bytes")

    return samples, rate

def write_wav_24bit(path, samples_stereo, sample_rate):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with wave.open(path, 'w') as wf:
        wf.setnchannels(2)
        wf.setsampwidth(3) # 24-bit
        wf.setframerate(sample_rate)
        raw = bytearray()
        max_val = 8388607
        min_val = -8388608
        for l, r in samples_stereo:
            cl = max(min_val, min(max_val, int(l * max_val)))
            cr = max(min_val, min(max_val, int(r * max_val)))
            raw.extend(cl.to_bytes(3, byteorder='little', signed=True))
            raw.extend(cr.to_bytes(3, byteorder='little', signed=True))
        wf.writeframes(raw)

def find_transient_onset(samples, expected_idx, search_window_samples, threshold_ratio=0.03):
    """Detects the exact transient attack within a small window around expected start."""
    start_search = max(0, expected_idx - int(search_window_samples * 0.15))
    end_search = min(len(samples), expected_idx + search_window_samples)

    # Find peak in the window
    peak = 0.0
    for i in range(start_search, end_search):
        amp = max(abs(samples[i][0]), abs(samples[i][1]))
        if amp > peak:
            peak = amp

    if peak < 0.0005: # near absolute silence
        return expected_idx

    # Find where signal rises above threshold_ratio * peak
    thresh = peak * threshold_ratio
    for i in range(start_search, end_search):
        amp = max(abs(samples[i][0]), abs(samples[i][1]))
        if amp >= thresh:
            # Step back 1.5ms pre-roll to preserve attack transient click
            preroll = int(0.0015 * 44100)
            return max(0, i - preroll)

    return expected_idx

def slice_and_build(render_wav_path, manifest_path, output_kit_dir, kit_title="EZD Extracted Kit"):
    print(f"=== GlorpDrums Kit Builder ===")
    print(f"Reading rendered WAV: {render_wav_path}")
    print(f"Reading manifest:     {manifest_path}")

    with open(manifest_path, 'r') as f:
        manifest = json.load(f)

    samples, sample_rate = read_wav_frames(render_wav_path)
    total_audio_sec = len(samples) / float(sample_rate)
    print(f"Audio loaded: {len(samples)} frames ({total_audio_sec:.2f} seconds) at {sample_rate} Hz")

    events = manifest["events"]
    instruments_data = {} # inst_name -> list of samples info

    search_window = int(0.12 * sample_rate) # 120ms search window around expected hit

    for ev_idx, ev in enumerate(events):
        inst_name = ev["instrument"]
        sample_name = ev["sample_name"]
        norm_power = ev["normalized_power"]
        expected_sec = ev["start_time_sec"]
        dur_sec = ev["duration_sec"]

        expected_frame = int(expected_sec * sample_rate)
        if expected_frame >= len(samples):
            print(f"Warning: Audio file ended early at event {ev_idx} ({inst_name} {sample_name})")
            break

        # Detect precise onset
        onset_frame = find_transient_onset(samples, expected_frame, search_window)
        num_frames = int(dur_sec * sample_rate)
        end_frame = min(len(samples), onset_frame + num_frames)

        sliced = samples[onset_frame:end_frame]
        if not sliced:
            continue

        # Apply smooth fadeout at the end (last 45ms)
        fadeout_len = min(len(sliced), int(0.045 * sample_rate))
        for k in range(fadeout_len):
            idx = len(sliced) - fadeout_len + k
            factor = 0.5 * (1.0 + math.cos(math.pi * k / float(fadeout_len)))
            l, r = sliced[idx]
            sliced[idx] = (l * factor, r * factor)

        # Write WAV file
        rel_wav = f"samples/{sample_name}.wav"
        out_wav_path = os.path.join(output_kit_dir, inst_name, rel_wav)
        write_wav_24bit(out_wav_path, sliced, sample_rate)

        if inst_name not in instruments_data:
            instruments_data[inst_name] = {
                "group": ev.get("group"),
                "chokes": ev.get("chokes", []),
                "note": ev.get("note", 36),
                "samples": []
            }

        instruments_data[inst_name]["samples"].append({
            "name": sample_name,
            "power": norm_power,
            "rel_wav": rel_wav
        })

    # -----------------------------------------------------------------------
    # Generate DrumGizmo Instrument XML files
    # -----------------------------------------------------------------------
    for inst_name, data in instruments_data.items():
        inst_dir = os.path.join(output_kit_dir, inst_name)
        samples_xml = ""
        for s in data["samples"]:
            samples_xml += f"""    <sample name="{s['name']}" power="{s['power']:.2f}">
      <audiofile channel="OHL" file="{s['rel_wav']}" filechannel="1"/>
      <audiofile channel="OHR" file="{s['rel_wav']}" filechannel="2"/>
    </sample>\n"""

        inst_xml_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<instrument version="2.0">
  <metadata>
    <title>{inst_name}</title>
  </metadata>
  <samples>
{samples_xml}  </samples>
</instrument>
"""
        with open(os.path.join(inst_dir, f"{inst_name}.xml"), 'w') as f:
            f.write(inst_xml_content)

    # -----------------------------------------------------------------------
    # Generate DrumGizmo drumkit.xml
    # -----------------------------------------------------------------------
    inst_nodes = ""
    for inst_name, data in instruments_data.items():
        group_attr = f' group="{data["group"]}"' if data["group"] else ""
        chokes_xml = ""
        if data["chokes"]:
            chokes_inner = "\n".join([f'        <choke instrument="{target}" choketime="{ctime}"/>'
                                      for target, ctime in data["chokes"]])
            chokes_xml = f"      <chokes>\n{chokes_inner}\n      </chokes>\n"

        file_rel = f"{inst_name}/{inst_name}.xml"
        inst_nodes += f"""    <instrument name="{inst_name}"{group_attr} file="{file_rel}">
{chokes_xml}      <channelmap in="OHL" out="OHL" main="true"/>
      <channelmap in="OHR" out="OHR" main="true"/>
    </instrument>\n"""

    drumkit_xml = f"""<?xml version="1.0" encoding="UTF-8"?>
<drumkit samplerate="{sample_rate}" version="2.1.0">
  <metadata>
    <version>1.0.0</version>
    <title>{kit_title}</title>
    <description>Extracted kit generated with GlorpDrums Sample Ripper</description>
    <author>GlorpDrums</author>
  </metadata>
  <channels>
    <channel name="OHL"><title>Overhead Left</title></channel>
    <channel name="OHR"><title>Overhead Right</title></channel>
  </channels>
  <instruments>
{inst_nodes}  </instruments>
</drumkit>
"""
    with open(os.path.join(output_kit_dir, "drumkit.xml"), 'w') as f:
        f.write(drumkit_xml)

    # -----------------------------------------------------------------------
    # Generate midimap.xml
    # -----------------------------------------------------------------------
    midimap_nodes = ""
    for inst_name, data in instruments_data.items():
        midimap_nodes += f'  <map note="{data["note"]}" instr="{inst_name}"/>\n'

    midimap_xml = f"""<?xml version="1.0" encoding="UTF-8"?>
<midimap>
{midimap_nodes}</midimap>
"""
    with open(os.path.join(output_kit_dir, "midimap.xml"), 'w') as f:
        f.write(midimap_xml)

    total_samples = sum(len(d["samples"]) for d in instruments_data.values())
    print(f"\n[SUCCESS] Drum kit created successfully at: {output_kit_dir}")
    print(f"  Instruments: {len(instruments_data)}")
    print(f"  Total sliced samples: {total_samples}")
    print(f"  Drumkit XML: {os.path.join(output_kit_dir, 'drumkit.xml')}")
    print(f"  Midimap XML: {os.path.join(output_kit_dir, 'midimap.xml')}")

if __name__ == "__main__":
    if len(sys.argv) < 4:
        print("Usage: python3 slice_and_build_kit.py <rendered.wav> <manifest.json> <output_kit_dir> [kit_title]")
        sys.exit(1)

    wav = sys.argv[1]
    mani = sys.argv[2]
    out = sys.argv[3]
    title = sys.argv[4] if len(sys.argv) > 4 else "EZD Extracted Kit"
    slice_and_build(wav, mani, out, title)
